#!/usr/bin/env python3
"""
End‑to‑end driver to collect training data from a batch of TPTP FOF problems.

This script automates the following steps for each problem listed in a JSON
file (such as the one extracted from TPTP index pages):

1. Launch the external agent (EA) implemented in ``process_iprover_v3.py`` in
   interactive mode.  The EA listens on a chosen TCP port and assigns
   heuristic scores to candidate clauses using a dry‑run of the ranker,
   avoiding any calls to large language models.  The EA also logs all
   messages exchanged between iProver and the EA to a specified log file.

2. Run iProver in interactive mode on the given problem file, configured to
   talk to the EA via the chosen port.  iProver will send clause
   registration, passive/given/simplified events and, if a proof is found,
   the list of clauses that form the proof.  The EA uses the scores to
   guide the search.

3. When iProver terminates (either by finding a proof, giving up, or
   reaching a timeout), the EA also exits (thanks to the ``--exit-on-finish``
   flag).  We then parse the raw log generated by the EA to extract clause
   labels (positive/negative) using the helper in ``iplog_to_dataset.py``.

4. Append the labeled examples to a cumulative JSONL output file.  Each
   example includes the problem name, the clause id, basic id, textual
   representation, clause features, the binary label, and a fine‑grained
   negative bucket when applicable.

**Port management**
```````````````````
Because both iProver and the EA communicate over a TCP socket, this script
reserves a free port for each problem by binding a temporary socket.  This
avoids conflicts when running multiple problems in sequence.  After the
reservation, the socket is closed and the chosen port is passed to both
processes.

**Usage example**::

    python run_batch_pipeline.py \
        --problems fof_problems_from_html.json \
        --iprover iproveropt \
        --output dataset.jsonl \
        --limit 10 

Note that this script assumes that ``iproveropt`` (or ``iprover``) is in
your PATH.  On systems where iProver is not installed, the call will
fail; in that case you can still use the helper ``iplog_to_dataset.py``
directly on previously collected logs.
"""

import argparse
import json
import os
import socket
import subprocess
import sys
import time
from pathlib import Path
from typing import List, Dict, Any, Optional

# We will write entries about failed runs to a separate JSONL file.  To
# facilitate this, we provide a few small helper functions below.  If
# failures should be ignored, these functions will not be invoked.

def _append_jsonl(path: str, obj: dict) -> None:
    """Append a single JSON object to a JSONL file.

    Ensures the directory exists before writing.  The object is serialized
    using UTF‑8 and ascii preservation is disabled to allow non‑ASCII
    clause text in logs.  A newline is appended after each JSON record.
    """
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "a", encoding="utf-8") as f:
        f.write(json.dumps(obj, ensure_ascii=False) + "\n")


def extract_last_given(log_path: str, limit: int = 32) -> List[int]:
    """Extract the last few given_clause IDs from a raw log.

    When a run fails to produce a proof, it can be helpful to inspect the
    clauses that were most recently selected as "given".  This function
    parses the raw log in reverse, collecting up to ``limit`` clause
    identifiers from the final given_clause events.  If the log cannot be
    read or contains no such events, an empty list is returned.
    """
    if not os.path.exists(log_path):
        return []
    try:
        with open(log_path, "rb") as f:
            data = f.read()
        # split on NUL; iterate segments from the end
        parts = [seg for seg in data.split(b"\x00") if seg.strip()]
        last_ids: List[int] = []
        for segment in reversed(parts):
            for line in reversed(segment.splitlines()):
                line = line.strip()
                if not line:
                    continue
                try:
                    msg = json.loads(line.decode("utf-8", errors="ignore"))
                except Exception:
                    continue
                if msg.get("tag") == "given_clause":
                    for cid in msg.get("clause_ids", []) or []:
                        try:
                            last_ids.append(int(cid))
                        except Exception:
                            pass
                    if len(last_ids) >= limit:
                        break
            if len(last_ids) >= limit:
                break
        # We reversed segments and lines, so the collected IDs are newest first.
        return list(reversed(last_ids[-limit:]))
    except Exception:
        return []


def log_failure(
    fail_log_path: str,
    *,
    problem_name: str,
    file_path: str,
    domain: Optional[str],
    reason: str,
    timeout_sec: Optional[int],
    elapsed_sec: Optional[float],
    iprover_exit: Optional[int],
    external_port: Optional[int],
    log_path: Optional[str],
) -> None:
    """Record a failed problem run to a JSONL file.

    Each failure entry includes identifying information about the problem,
    the reason for failure ("timeout", "iprover_error", or "no_proof"),
    timing information, the external port used, the path to the raw log,
    and a timestamp.  To aid manual triage, the last few given clause IDs
    (if any) are extracted and included.  The function writes one line
    per failure to ``fail_log_path``.
    """
    entry: Dict[str, Any] = {
        "problem_name": problem_name,
        "file_path": file_path,
        "domain": domain,
        "reason": reason,
        "timeout_sec": timeout_sec,
        "elapsed_sec": elapsed_sec,
        "iprover_exit": iprover_exit,
        "external_port": external_port,
        "log_path": log_path,
        "timestamp": int(time.time()),
        "note": "manual_proof_needed",
    }
    # Attach recent given_clause IDs to help locate promising negatives
    if log_path:
        entry["last_given_ids"] = extract_last_given(log_path, limit=32)
    else:
        entry["last_given_ids"] = []
    _append_jsonl(fail_log_path, entry)


def has_proof_out(path: str) -> bool:
    """Check if the raw log contains a proof_out event.

    Since parsing the entire log as JSON can be expensive, we do a simple
    byte scan for the substring '"proof_out"'.  This is sufficient to
    detect whether a proof was emitted by iProver.  If the file does not
    exist, returns False.
    """
    if not os.path.exists(path):
        return False
    try:
        with open(path, "rb") as f:
            data = f.read()
        return b'"proof_out"' in data
    except Exception:
        return False

